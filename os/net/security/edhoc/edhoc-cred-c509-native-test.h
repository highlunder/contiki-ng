/**
 * \file
 *   EDHOC test credentials — native C509 Type 2 (natively signed) chain.
 *
 *   "Type 2" refers to a natively-signed C509 certificate
 *   (draft-ietf-cose-cbor-encoded-cert §3.1): the ECDSA signature is
 *   computed directly over SHA-256(CBOR TBS fields 0-9), with no
 *   intermediate X.509 DER encoding involved. This is in contrast to
 *   "Type 3" certificates, which are reconstructed-DER-equivalent (the
 *   signature covers a DER TBSCertificate that can be losslessly rebuilt
 *   from the C509 fields). See edhoc-cred-c509-test.h for a Type-3 example.
 *
 *   Generated by: cargo run -- g  (CBOR-certificates/c509_demo_impl)
 *
 *   Chain: EDHOC-Test-CA (self-signed) -> Client / Server (issued by CA)
 *   Curve: secp256r1 (P-256), sigAlg: ecdsa-with-SHA256 (C509 id 0)
 *   KID:   CA=0x01, Client=0x03, Server=0x04
 *   Type 2 signature: ECDSA-P256 over SHA-256(concat(CBOR fields 0-9))
 *   notBefore: POSIX 1700000000 (~2023-11-14)
 *   notAfter:  POSIX 2000000000 (~2033-05-18)
 *
 *   Exported symbols:
 *   - c509_native_ca_cert            : CA cert bytes (Type 2, self-signed),
 *                                       used as the trust anchor.
 *   - C509_NATIVE_CA_PUB_X/Y          : CA public key coordinates, for
 *                                       building an edhoc_trust_store_t
 *                                       (see edhoc-trust-store.h).
 *   - c509_native_ca_pubkey           : cose_key_t trust-anchor entry
 *                                       wrapping the CA public key
 *                                       (private key field is all-zero).
 *   - c509_native_client_cert /
 *     c509_native_server_cert         : leaf cert bytes (Type 2, CA-issued)
 *                                       for the client and server.
 *   - C509_NATIVE_CLIENT_* / SERVER_*  : raw private/public key material
 *                                       (priv key, pub X/Y) for each leaf,
 *                                       and RFC 5915 DER-encoded private
 *                                       keys for mbedtls_pk_parse_key().
 *   - auth_c509_native_client_template/
 *     auth_c509_native_server_template: cose_key_t templates combining KID,
 *                                       identity and key material; c509_data
 *                                       /c509_len must be filled in at
 *                                       runtime via the attach helpers below.
 *   - c509_native_client_attach_cert()/
 *     c509_native_server_attach_cert(): set c509_data/c509_len on a
 *                                       cose_key_t to point at the
 *                                       corresponding leaf cert above.
 *
 *   SECURITY NOTICE: Test credentials only. Never use in production.
 *
 * \author Joel Höglund <joel.hoglund@ri.se>
 */

