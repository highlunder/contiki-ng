/**
 * \file
 *   Test credentials for X.509-based EDHOC authentication (x5chain mode).
 *
 *   SECURITY NOTICE: These credentials are for testing purposes ONLY.
 *   The private key is publicly known. Never use in production.
 *
 *   Cert: self-signed X.509 v3 DER (RFC 5280), P-256/secp256r1, 384 bytes.
 *   Same key material and subject CN as c509_test_cert in
 *   edhoc-cred-c509-test.h, so that scenario C (EDHOC+OSCORE+X.509) and
 *   scenario D (EDHOC+OSCORE+C509) use apples-to-apples credentials
 *   differing only in encoding.
 *
 *   Note: a first attempt reused the DER reconstruction produced by
 *   `cargo run -- c <hex>` (C509 Type-3 -> DER) from c509_test_cert, but
 *   that reconstruction carries over the *original* C509 signature bytes,
 *   which were computed over the C509-encoded TBS — not the DER-encoded
 *   TBS — so the reconstructed cert fails self-signed verification in DER
 *   form. This cert is instead freshly self-signed (openssl req -x509)
 *   over its own DER TBSCertificate, using the same priv/pub key, so
 *   `edhoc_x509_validate_self_signed()` succeeds.
 *
 * \author Joel Höglund <joel.hoglund@ri.se>
 */

