/**
 * \file
 *   Test credentials for X.509-based EDHOC authentication (x5chain mode)
 *   with a chain-length-1 certificate chain (scenario C chain variant,
 *   the X.509 counterpart of edhoc-cred-c509-test-chain.h).
 *
 *   SECURITY NOTICE: These credentials are for testing purposes ONLY.
 *   The private keys are publicly known. Never use in production.
 *
 *   Chain: Test-Root-CA (trust anchor, out-of-band)
 *            -> Test-Sub-CA -> Client / Server
 *   On the wire (x5chain CRED_x), each peer sends [bstr<leaf cert>,
 *   bstr<Sub CA cert>] as a CBOR array, i.e.
 *   ID_CRED_x = {33: [bstr<leaf>, bstr<Sub CA>]}. The Root CA public key is
 *   the out-of-band trust anchor, registered via
 *   edhoc_set_c509_trust_store() together with edhoc_x509_validate_chain()
 *   as the cert validator.
 *
 *   Same EC key scalars as c509-native-chain-test.h (Root/Sub CA/Client/
 *   Server), so that scenario C (EDHOC+OSCORE+X.509) and scenario D
 *   (EDHOC+OSCORE+C509) chain-length-1 variants use apples-to-apples
 *   credentials differing only in encoding. The DER certs below are
 *   freshly issued (openssl req/x509, RFC 5280) over those same keys,
 *   forming a Root CA -> Sub CA -> {Client, Server} chain.
 *
 * \author Joel Höglund <joel.hoglund@ri.se>
 */

