/*---------------------------------------------------------------------------*/
/* Buffer for the on-wire x5chain CRED_x: CBOR array [bstr<leaf>, bstr<Sub CA>].
 * Sizing: 1 (array(2) header) + 3 (bstr header, len 381) + 381 (leaf)
 *       + 3 (bstr header, len 394) + 394 (Sub CA) = 782 bytes -> 800 (margin).
 */
#define X509_CHAIN_CRED_BUF_LEN 800

static uint8_t x509_chain_client_cred_buf[X509_CHAIN_CRED_BUF_LEN];
static uint8_t x509_chain_server_cred_buf[X509_CHAIN_CRED_BUF_LEN];

/*---------------------------------------------------------------------------*/
/* Build CRED_x = CBOR array [bstr<leaf>, bstr<sub_ca>] into buf, and point
 * key->c509_data/c509_len at it. Used for both x5chain CRED_x/ID_CRED_x
 * generation (edhoc_x509_generate_cred_x()/edhoc_x509_generate_id_cred_x5chain())
 * on the sending side. */
static inline void
x509_chain_test_build_cred(cose_key_t *key,
                            const uint8_t *leaf, size_t leaf_len,
                            uint8_t *buf, size_t buf_sz)
{
  cbor_writer_state_t w;
  cbor_init_writer(&w, buf, buf_sz);
  cbor_open_array(&w);
  cbor_write_data(&w, leaf, leaf_len);
  cbor_write_data(&w, x509_chain_sub_ca_cert, sizeof(x509_chain_sub_ca_cert));
  cbor_close_array(&w);
  size_t written = cbor_end_writer(&w);

  key->c509_data = buf;
  key->c509_len  = written;
}

/*---------------------------------------------------------------------------*/
/* Attach the [client cert, Sub CA cert] chain to a key at runtime.
 * Call this for the client's own key before edhoc_add_key()/edhoc_setup_key_pair(). */
static inline void
x509_chain_test_attach_client_cert(cose_key_t *key)
{
  x509_chain_test_build_cred(key,
                              x509_chain_client_cert,
                              sizeof(x509_chain_client_cert),
                              x509_chain_client_cred_buf,
                              sizeof(x509_chain_client_cred_buf));
}

/*---------------------------------------------------------------------------*/
/* Attach the [server cert, Sub CA cert] chain to a key at runtime.
 * Call this for the server's own key before edhoc_add_key()/edhoc_setup_key_pair(). */
static inline void
x509_chain_test_attach_server_cert(cose_key_t *key)
{
  x509_chain_test_build_cred(key,
                              x509_chain_server_cert,
                              sizeof(x509_chain_server_cert),
                              x509_chain_server_cred_buf,
                              sizeof(x509_chain_server_cred_buf));
}

