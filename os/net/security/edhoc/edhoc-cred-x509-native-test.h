/**
 * \file
 *   Test credentials — plain X.509 DER chain, scenario A (DTLS+X.509)
 *   for the C509 evaluation lossy-radio sweep (PLAN-c509-lice-followup.md
 *   sec. 5.3.5).
 *
 *   This chain is generated by openssl over the *same* P-256 keypairs as
 *   the C509 native Type-2 chain in edhoc-cred-c509-native-test.h, so the
 *   on-the-wire DTLS handshake sizes can be compared apples-to-apples
 *   against scenarios B/C/D (the C509-based scenarios all use the same
 *   CA/Client/Server keypairs).
 *
 *   Chain: EDHOC-Test-CA (self-signed, CA:TRUE) -> Client / Server
 *          (issued by CA)
 *   Curve: secp256r1 (P-256), sigAlg: ecdsa-with-SHA256
 *   notBefore: POSIX 1700000000 (~2023-11-14)
 *   notAfter:  POSIX 2000000000 (~2033-05-18)
 *
 *   Generated via:
 *     openssl req -new -x509 ...   (self-signed CA, CA:TRUE)
 *     openssl ca ...                (CA-issued Client / Server leafs)
 *   with default_startdate/default_enddate set to the validity window
 *   above. See paper_space/PLAN-c509-lice-followup.md sec. 5.3.5 for the
 *   exact commands.
 *
 *   Exported symbols:
 *   - x509_native_ca_cert             : CA cert DER (self-signed, CA:TRUE),
 *                                        trust anchor for coap_get_cert_info.
 *   - x509_native_client_cert /
 *     x509_native_server_cert         : leaf cert DER (CA-issued).
 *   - x509_native_client_priv_key_der /
 *     x509_native_server_priv_key_der : RFC 5915 DER-encoded EC private
 *                                        keys (no embedded public key field;
 *                                        OPTIONAL per RFC 5915, mbedTLS
 *                                        derives it), for
 *                                        mbedtls_pk_parse_key().
 *
 *   SECURITY NOTICE: Test credentials only. Never use in production.
 *
 * \author Joel Höglund <joel.hoglund@ri.se>
 */

